// Signing: the same key must sign every build, or Android refuses to update the installed
// app (and you'd lose your data reinstalling). CI supplies it from repository secrets;
// local builds fall back to the debug key.
val ksFile = System.getenv("COMPOUND_KEYSTORE")?.let { file(it) }

android {
    namespace = "com.compound.finance"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.compound.finance"
        minSdk = 26
        targetSdk = 35
        versionCode = (System.getenv("GITHUB_RUN_NUMBER") ?: "1").toInt()
        versionName = "1.0." + (System.getenv("GITHUB_RUN_NUMBER") ?: "0")
    }

    signingConfigs {
        if (ksFile != null && ksFile.exists()) {
            create("release") {
                storeFile = ksFile
                storePassword = System.getenv("COMPOUND_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("COMPOUND_KEY_ALIAS") ?: "compound"
                keyPassword = System.getenv("COMPOUND_KEY_PASSWORD") ?: System.getenv("COMPOUND_KEYSTORE_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures { compose = true }
    testOptions { unitTests.isReturnDefaultValues = true }
}

